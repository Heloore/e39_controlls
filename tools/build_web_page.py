#!/usr/bin/env python3
"""Compresses tools/web_page.html into sketch_sep11b/WebPage.h (gzip bytes the ESP32 sends as is).

Run after every change of the page:  python3 tools/build_web_page.py
"""
import gzip
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tools" / "web_page.html"
TARGET = ROOT / "sketch_sep11b" / "WebPage.h"
BYTES_PER_LINE = 24


def main():
    html = SOURCE.read_bytes()
    packed = gzip.compress(html, compresslevel=9, mtime=0)
    lines = []
    for start in range(0, len(packed), BYTES_PER_LINE):
        chunk = packed[start:start + BYTES_PER_LINE]
        lines.append("  " + ", ".join(f"0x{byte:02x}" for byte in chunk))
    TARGET.write_text(
        "#pragma once\n\n"
        "#include <pgmspace.h>\n\n"
        "// Generated by tools/build_web_page.py from tools/web_page.html. Do not edit by hand.\n"
        "// Gzip keeps the page small enough for the little heap left next to Bluetooth.\n"
        f"constexpr size_t WEB_PAGE_GZ_LENGTH = {len(packed)};\n"
        "const uint8_t WEB_PAGE_GZ[] PROGMEM = {\n" + ",\n".join(lines) + "\n};\n"
    )
    print(f"{len(html)} bytes of HTML -> {len(packed)} bytes gzip -> {TARGET}")


main()
